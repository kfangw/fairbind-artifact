#!/usr/bin/env python3
"""Generates the reference contract's tests for the anchor variants (K13).

For each variant (C1, C1r) the behaviour tests under contracts/test/sdk are
copied into contracts/test/sdk/variants/<variant>/ with three changes only:
the settlement contract type is the variant's, the contract is deployed with
its module apart, calls the variant moved across the module split go to the
other handle, and the five calls that take a stored record back in
calldata (anchorUnit, prove, openDispute, proveSwap, proveDoubleSign) go
through helpers that add the records the variant emitted. Test bodies and
assertions are unchanged. Run from the repository root:

    python3 contracts/test/sdk/variants/gen_tests.py
"""
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent
SDK = ROOT.parent
TESTS = [
    "CheckCases.t.sol",
    "FailureCases.t.sol",
    "KCases.t.sol",
    "RuleCases.t.sol",
    "SettlementCases.t.sol",
    "VerifierCases.t.sol",
]
VARIANTS = {"c1": ("SampledSettlementC1", "SampledSettlementC1.sol", "false"),
            "c1r": ("SampledSettlementC1r", "SampledSettlementC1r.sol", "true")}

HEADER = "// Generated by contracts/test/sdk/variants/gen_tests.py from contracts/test/sdk/{src}; do not edit.\n"

ALIASES = """// SPDX-License-Identifier: MIT
pragma solidity ^0.8.24;
// Generated by contracts/test/sdk/variants/gen_tests.py; do not edit.

import {{ {main} as SampledSettlementV }} from "../{mainfile}";
import {{
    SettlementModuleC1 as SettlementModuleV,
    SettlementModuleC1 as SettlementModuleRealV,
    SettlementBaseC1 as SettlementBaseV,
    UnitRec,
    EpochRec,
    AnchorPre
}} from "../SampledSettlementC1.sol";
import {{
    IAuthToken,
    ReceivingVault,
    Profile,
    Receipt,
    Leaf,
    Unit,
    Opening,
    Auth,
    UnitHeader,
    Account,
    Freeze
}} from "../../SampledSettlement.sol";
"""

HELPERS = """
    // ------------------------------------------- variant records (K13)

    bool internal constant REUSE_V = {reuse};
    VVm internal constant vvm = VVm(address(uint160(uint256(keccak256("hevm cheat code")))));
    mapping(bytes32 => UnitRec) internal _urecV; // (pid, epoch, unit) => record emitted at the store
    mapping(bytes32 => EpochRec) internal _erecV; // (pid, epoch) => latest epoch record

    function _ukV(bytes32 pid, uint256 e, uint256 u) internal pure returns (bytes32) {{
        return keccak256(abi.encode(pid, e, u));
    }}

    function _ekV(bytes32 pid, uint256 e) internal pure returns (bytes32) {{
        return keccak256(abi.encode(pid, e));
    }}

    /// The module first, for the settlement contract's address, then the
    /// settlement contract.
    function _newV(IAuthToken t, address r) internal returns (SampledSettlementV x) {{
        address at = vvm.computeCreateAddress(address(this), vvm.getNonce(address(this)) + 1);
        SettlementModuleRealV md = new SettlementModuleRealV(t, r, block.number, at, REUSE_V);
        x = new SampledSettlementV(t, r, address(md));
        require(address(x) == at, "module address");
    }}

    function _absorbV() internal {{
        VLog[] memory logs = vvm.getRecordedLogs();
        for (uint256 i; i < logs.length; i++) {{
            if (logs[i].emitter != address(f) || logs[i].topics.length == 0) continue;
            if (logs[i].topics[0] == SettlementBaseV.UnitRecorded.selector) {{
                UnitRec memory r = abi.decode(logs[i].data, (UnitRec));
                _urecV[_ukV(r.pid, r.epoch, r.unitNo)] = r;
            }} else if (logs[i].topics[0] == SettlementBaseV.EpochRecorded.selector) {{
                EpochRec memory r = abi.decode(logs[i].data, (EpochRec));
                _erecV[_ekV(r.pid, r.epoch)] = r;
            }}
        }}
    }}

    function _anchorV(Unit memory u) internal returns (uint8 reason) {{
        AnchorPre memory pre;
        pre.er = _erecV[_ekV(u.pid, u.epoch)];
        if (u.unitNo > 0) pre.prev = _urecV[_ukV(u.pid, u.epoch, u.unitNo - 1)];
        pre.next = _urecV[_ukV(u.pid, u.epoch, uint256(u.unitNo) + 1)];
        vvm.recordLogs();
        reason = f.anchorUnit(u, pre);
        _absorbV();
    }}

    function _recV(bytes32 pid, uint256 e, uint256 u) internal view returns (UnitRec memory) {{
        return _urecV[_ukV(pid, e, u)];
    }}

    function _proveV(Opening memory o, bytes memory material) internal {{
        UnitRec memory r = _recV(o.pid, o.epoch, o.unitNo);
        f.prove(o, material, r);
    }}

    function _openDisputeV(Opening memory o, uint8 kind, bytes memory mandate, uint8 kinds) internal {{
        UnitRec memory r = _recV(o.pid, o.epoch, o.unitNo);
        f.openDispute(o, kind, mandate, kinds, r);
    }}

    function _proveSwapV(Opening memory o, Receipt memory rs, bytes memory sig) internal {{
        UnitRec memory r = _recV(o.pid, o.epoch, o.unitNo);
        m.proveSwap(o, rs, sig, r);
    }}

    function _proveDoubleSignV(UnitHeader memory h, bytes memory sig) internal {{
        UnitRec memory r = _recV(h.pid, h.epoch, h.unitNo);
        m.proveDoubleSign(h, sig, r);
    }}
}}
"""

VVM = """
struct VLog {
    bytes32[] topics;
    bytes data;
    address emitter;
}

interface VVm {
    function computeCreateAddress(address deployer, uint256 nonce) external pure returns (address);
    function getNonce(address account) external view returns (uint64);
    function recordLogs() external;
    function getRecordedLogs() external returns (VLog[] memory);
}
"""

CALLS = [
    (r"\bf\.anchorUnit\(", "_anchorV("),
    (r"\bf\.prove\(", "_proveV("),
    (r"\bf\.openDispute\(", "_openDisputeV("),
    (r"\bm\.proveSwap\(", "_proveSwapV("),
    (r"\bm\.proveDoubleSign\(", "_proveDoubleSignV("),
    (r"new SampledSettlement\(", "_newV("),
    # calls the variant places on the other side of the module split (code size)
    (r"\bf\.register\(", "m.register("),
    (r"\bf\.profile\(", "m.profile("),
    (r"\bf\.sale\(", "m.sale("),
    (r"\bf\.vaultAddress\(", "m.vaultAddress("),
    (r"\bf\.epochNonces\(", "m.epochNonces("),
    (r"\bm\.depositBond\(", "f.depositBond("),
    (r"\bm\.reenter\(", "f.reenter("),
    (r"\bm\.claimDeadline\(", "f.claimDeadline("),
    (r"\bm\.claimFrozen\(", "f.claimFrozen("),
]


def common(text, suffix, local_names):
    text = text.replace('"./SampledSettlement.sol"', '"./V.sol"')
    text = text.replace('"./MockAuthToken.sol"', '"../../MockAuthToken.sol"')
    text = text.replace('"../g10/', '"../../../g10/').replace('"../g7/', '"../../../g7/')
    for pat, rep in CALLS:
        text = re.sub(pat, rep, text)
    text = re.sub(r"\bSampledSettlement\b", "SampledSettlementV", text)
    text = re.sub(r"\bSettlementModule\b", "SettlementModuleV", text)
    text = re.sub(r"\bSettlementBase\b", "SettlementBaseV", text)
    text = re.sub(r"\bSdkBase\b", "SdkBase" + suffix, text)
    for n in local_names:
        text = re.sub(r"\b%s\b" % n, n + suffix, text)
    return text


def main():
    for v, (cname, cfile, reuse) in VARIANTS.items():
        suffix = v.upper()
        out = ROOT / v
        out.mkdir(exist_ok=True)
        (out / "V.sol").write_text(ALIASES.format(main=cname, mainfile=cfile))
        base = (SDK / "SdkBase.sol").read_text()
        base = common(base, suffix, ["SdkVm"])
        # the records the helpers need, and the variant structs
        base = base.replace(
            'import { SampledSettlementV, SettlementModuleV, Profile, Receipt, Leaf, Unit, Opening, Auth, IAuthToken } from "./V.sol";',
            'import {\n    SampledSettlementV,\n    SettlementModuleV,\n    SettlementBaseV,\n    SettlementModuleRealV,\n    Profile,\n    Receipt,\n    Leaf,\n    Unit,\n    Opening,\n    Auth,\n    IAuthToken,\n    UnitHeader,\n    UnitRec,\n    EpochRec,\n    AnchorPre\n} from "./V.sol";',
        )
        assert "UnitRec," in base, "SdkBase import line changed"
        base = base.replace("\ninterface SdkVm" + suffix, VVM + "\ninterface SdkVm" + suffix, 1)
        assert base.rstrip().endswith("}")
        base = base.rstrip()[:-1] + HELPERS.format(reuse=reuse)
        lines = base.split("\n", 1)
        (out / ("SdkBase" + suffix + ".sol")).write_text(lines[0] + "\n" + HEADER.format(src="SdkBase.sol") + lines[1])
        for t in TESTS:
            text = (SDK / t).read_text()
            names = re.findall(r"^(?:contract|interface|abstract contract)\s+(\w+)", text, re.M)
            text = common(text, suffix, names)
            lines = text.split("\n", 1)
            (out / t).write_text(lines[0] + "\n" + HEADER.format(src=t) + lines[1])


if __name__ == "__main__":
    main()
