#!/usr/bin/env python3
"""Builds the fixture of StorageProofGas.t.sol from a local anvil node.

anvil (Foundry 1.5.1, --hardfork prague) does not run the EIP-2935 system
call, so this script installs the EIP-2935 runtime code at the history
contract address and writes its ring buffer itself: slot (n mod 8191) holds
the hash of block n for the 8,191 blocks before the measured block B. It also
adds N_ACCOUNTS funded accounts so that the account trie has some depth. It
then takes block B's header (RLP, checked against its hash with cast keccak)
and eth_getProof for the history contract and one slot, and for a few plain
accounts (depth only). No external data is used.

usage: gen_storage_proof.py <rpc url> <out .sol> [n_accounts]
"""
import json, subprocess, sys, urllib.request, random

RPC = sys.argv[1]
OUT = sys.argv[2]
N_ACCOUNTS = int(sys.argv[3]) if len(sys.argv) > 3 else 100000
HISTORY = "0x0000F90827F1C53a10cb7A02335B175320002935"
CODE = ("0x3373fffffffffffffffffffffffffffffffffffffffe14604657602036036042575f3560014303"
        "8111604257611fff81430311604257611fff9006545f5260205ff35b5f5ffd5b5f35611fff60014303065500")
WINDOW = 8191
_id = 0


def call(batch):
    global _id
    body = []
    for m, p in batch:
        _id += 1
        body.append({"jsonrpc": "2.0", "id": _id, "method": m, "params": p})
    req = urllib.request.Request(RPC, json.dumps(body).encode(), {"Content-Type": "application/json"})
    out = json.loads(urllib.request.urlopen(req, timeout=600).read())
    out.sort(key=lambda r: r["id"])
    for r in out:
        if "error" in r:
            raise RuntimeError(r["error"])
    return [r["result"] for r in out]


def one(m, p):
    return call([(m, p)])[0]


def chunks(xs, n):
    for i in range(0, len(xs), n):
        yield xs[i:i + n]


def rlp_bytes(b):
    if len(b) == 1 and b[0] < 0x80:
        return b
    return rlp_len(len(b), 0x80) + b


def rlp_len(n, off):
    if n < 56:
        return bytes([off + n])
    nb = n.to_bytes((n.bit_length() + 7) // 8, "big")
    return bytes([off + 55 + len(nb)]) + nb


def rlp_list(items):
    body = b"".join(items)
    return rlp_len(len(body), 0xC0) + body


def hx(s):
    s = s[2:] if s.startswith("0x") else s
    if len(s) % 2:
        s = "0" + s
    return bytes.fromhex(s)


def qty(s):
    v = int(s, 16)
    return b"" if v == 0 else v.to_bytes((v.bit_length() + 7) // 8, "big")


def header_rlp(b):
    f = [hx(b["parentHash"]), hx(b["sha3Uncles"]), hx(b["miner"]), hx(b["stateRoot"]),
         hx(b["transactionsRoot"]), hx(b["receiptsRoot"]), hx(b["logsBloom"]), qty(b["difficulty"]),
         qty(b["number"]), qty(b["gasLimit"]), qty(b["gasUsed"]), qty(b["timestamp"]), hx(b["extraData"]),
         hx(b["mixHash"]), hx(b["nonce"]), qty(b["baseFeePerGas"]), hx(b["withdrawalsRoot"]),
         qty(b["blobGasUsed"]), qty(b["excessBlobGas"]), hx(b["parentBeaconBlockRoot"]), hx(b["requestsHash"])]
    return rlp_list([rlp_bytes(x) for x in f])


def keccak(b):
    return subprocess.check_output(["cast", "keccak", "0x" + b.hex()]).decode().strip()


def main():
    random.seed(10)
    one("anvil_setCode", [HISTORY, CODE])
    one("anvil_mine", [hex(WINDOW + 200)])
    addrs = ["0x" + random.getrandbits(160).to_bytes(20, "big").hex() for _ in range(N_ACCOUNTS)]
    for c in chunks(addrs, 2000):
        call([("anvil_setBalance", [a, hex(10**18 + i)]) for i, a in enumerate(c)])
    last = int(one("eth_blockNumber", []), 16)
    nums = list(range(last - WINDOW + 1, last + 1))
    hashes = {}
    for c in chunks(nums, 500):
        res = call([("eth_getBlockByNumber", [hex(n), False]) for n in c])
        for n, r in zip(c, res):
            hashes[n] = r["hash"]
    for c in chunks(nums, 2000):
        call([("anvil_setStorageAt", [HISTORY, "0x" + (n % WINDOW).to_bytes(32, "big").hex(), hashes[n]]) for n in c])
    one("anvil_mine", ["0x1"])
    B = last + 1
    blk = one("eth_getBlockByNumber", [hex(B), False])
    hdr = header_rlp(blk)
    assert keccak(hdr) == blk["hash"], "header RLP does not hash to the block hash"
    ref = B - 4000  # a reference block inside the window
    slot = ref % WINDOW
    pr = one("eth_getProof", [HISTORY, ["0x" + slot.to_bytes(32, "big").hex()], hex(B)])
    sp = pr["storageProof"][0]
    assert int(sp["value"], 16) == int(hashes[ref], 16)
    depths = []
    byDepth = {}
    for a in addrs[:256]:
        ap = one("eth_getProof", [a, [], hex(B)])["accountProof"]
        depths.append(len(ap))
        byDepth.setdefault(len(ap), (a, ap))
    lines = ["// SPDX-License-Identifier: MIT", "pragma solidity ^0.8.24;", "",
             "// Generated by fixtures/gen_storage_proof.py from a local anvil node", 
             f"// ({N_ACCOUNTS} added accounts, EIP-2935 ring buffer of {WINDOW} slots written by the script).",
             f"// Account proof depths of 256 plain accounts: min {min(depths)}, max {max(depths)}, "
             f"mean {sum(depths)/len(depths):.2f}.",
             "library StorageProofFixture {",
             f"    bytes32 internal constant BLOCK_HASH = {blk['hash']};",
             f"    uint256 internal constant BLOCK_NUMBER = {B};",
             f"    uint256 internal constant REF_BLOCK = {ref};",
             f"    bytes32 internal constant REF_HASH = {hashes[ref]};",
             f"    uint256 internal constant SLOT = {slot};",
             f"    bytes32 internal constant STATE_ROOT = {blk['stateRoot']};",
             f"    bytes32 internal constant STORAGE_ROOT = {pr['storageHash']};",
             "    function header() internal pure returns (bytes memory) {",
             f'        return hex"{hdr.hex()}";', "    }",
             "    function accountProof() internal pure returns (bytes[] memory p) {",
             f"        p = new bytes[]({len(pr['accountProof'])});"]
    for i, n in enumerate(pr["accountProof"]):
        lines.append(f'        p[{i}] = hex"{n[2:]}";')
    lines += ["    }", "    function storageProof() internal pure returns (bytes[] memory p) {",
              f"        p = new bytes[]({len(sp['proof'])});"]
    for i, n in enumerate(sp["proof"]):
        lines.append(f'        p[{i}] = hex"{n[2:]}";')
    lines.append("    }")
    ds = sorted(byDepth)
    lines.append(f"    uint256 internal constant PLAIN_COUNT = {len(ds)};")
    lines.append("    function plain(uint256 i) internal pure returns (address a, bytes[] memory p) {")
    for j, d in enumerate(ds):
        a, ap = byDepth[d]
        lines.append(f"        if (i == {j}) {{")
        lines.append(f"            a = {subprocess.check_output(['cast', 'to-check-sum-address', a]).decode().strip()};")
        lines.append(f"            p = new bytes[]({len(ap)});")
        for k, n in enumerate(ap):
            lines.append(f'            p[{k}] = hex"{n[2:]}";')
        lines.append("        }")
    lines += ["    }", "}", ""]
    open(OUT, "w").write("\n".join(lines))
    print("block", B, "account proof nodes", len(pr["accountProof"]), "sizes",
          [len(hx(n)) for n in pr["accountProof"]], "storage proof nodes", len(sp["proof"]), "sizes",
          [len(hx(n)) for n in sp["proof"]], "plain depths", sorted(byDepth), [depths.count(d) for d in sorted(byDepth)], "header bytes", len(hdr))


main()
